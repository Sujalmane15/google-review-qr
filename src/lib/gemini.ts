import { GoogleGenAI } from "@google/genai";
import { ReviewSuggestionRequest, ReviewSuggestionResponse } from "@/types";

const SYSTEM_INSTRUCTION = `You generate optional draft Google review suggestions for a real customer.
Use ONLY details explicitly provided by the customer.
Never invent food items, services, employees, purchases, prices, events, or experiences.
Never pretend the customer experienced something they did not provide.
Do not pressure the customer into leaving a positive review.
Reflect the customer's selected rating and feedback honestly.
Generate exactly three distinct, natural-sounding drafts.
Avoid repetitive marketing language.
Do not mention that the text was generated by AI.
Keep each suggestion concise and easy for the customer to edit.
Output format: Return ONLY the three suggestions separated by the delimiter "---" without numbering, markdown prefixes, bullet points, or extra preamble.`;

/**
 * Deterministic fallback suggestions in case Gemini is offline or rate-limited.
 * Strictly adheres to only what the user selected, never inventing facts.
 */
function generateFallbackSuggestions(req: ReviewSuggestionRequest): string[] {
  const { businessName, rating, selectedTags, optionalCustomerText, language } = req;
  const note = optionalCustomerText ? ` ${optionalCustomerText}` : "";
  const tagList = selectedTags.length > 0 ? selectedTags.join(", ") : "";

  if (language === "mr") {
    if (rating >= 4) {
      return [
        `${businessName} येथे उत्तम अनुभव राहिला.${tagList ? ` विशेषतः ${tagList} आवडले.` : ""}${note}`,
        `चांगला अनुभव आला.${tagList ? ` ${tagList} छान होते.` : ""}${note} धन्यवाद!`,
        `${businessName} ची भेट छान ठरली.${tagList ? ` ${tagList} बद्दल समाधान वाटले.` : ""}${note}`,
      ];
    } else if (rating === 3) {
      return [
        `${businessName} येथे सर्वसाधारण अनुभव होता.${tagList ? ` ${tagList} ठीक होते.` : ""}${note}`,
        `अनुभव सामान्य राहिला.${tagList ? ` ${tagList} मध्ये अजून सुधारणा करता येईल.` : ""}${note}`,
        `${businessName} चा अनुभव ठीकठाक होता.${tagList ? ` ${tagList} सामान्य वाटले.` : ""}${note}`,
      ];
    } else {
      return [
        `${businessName} येथील अनुभव अपेक्षेप्रमाणे नव्हता.${tagList ? ` ${tagList} बाबतीत निराशा झाली.` : ""}${note}`,
        `सेवेत सुधारणेची गरज आहे.${tagList ? ` ${tagList} समाधानकारक नव्हते.` : ""}${note}`,
        `${businessName} येथे चांगला अनुभव आला नाही.${tagList ? ` ${tagList} बद्दल नाराजी आहे.` : ""}${note}`,
      ];
    }
  }

  if (language === "hi") {
    if (rating >= 4) {
      return [
        `${businessName} में बहुत अच्छा अनुभव रहा।${tagList ? ` विशेष रूप से ${tagList} पसंद आया।` : ""}${note}`,
        `काफी अच्छा अनुभव था।${tagList ? ` ${tagList} बढ़िया था।` : ""}${note} धन्यवाद!`,
        `${businessName} का अनुभव बहुत सुखद रहा।${tagList ? ` ${tagList} बहुत अच्छा लगा।` : ""}${note}`,
      ];
    } else if (rating === 3) {
      return [
        `${businessName} में औसत अनुभव रहा।${tagList ? ` ${tagList} ठीक-ठाक था।` : ""}${note}`,
        `अनुभव सामान्य था।${tagList ? ` ${tagList} में सुधार की गुंजाइश है।` : ""}${note}`,
        `${businessName} की सेवा ठीक थी लेकिन और बेहतर हो सकती है।${tagList ? ` ${tagList} सामान्य था।` : ""}${note}`,
      ];
    } else {
      return [
        `${businessName} में निराशाजनक अनुभव रहा।${tagList ? ` ${tagList} ठीक नहीं था।` : ""}${note}`,
        `यहाँ सेवा में सुधार की सख्त ज़रूरत है।${tagList ? ` ${tagList} बिल्कुल संतोषजनक नहीं था।` : ""}${note}`,
        `${businessName} में हमारा अनुभव अच्छा नहीं रहा।${tagList ? ` ${tagList} को लेकर काफी निराशा हुई।` : ""}${note}`,
      ];
    }
  }

  // English default
  if (rating >= 4) {
    return [
      `Great experience at ${businessName}.${tagList ? ` Really appreciated the ${tagList}.` : ""}${note}`,
      `Had a wonderful visit.${tagList ? ` The ${tagList} was very good.` : ""}${note} Would recommend!`,
      `Very pleased with ${businessName}.${tagList ? ` Nice ${tagList} and overall positive experience.` : ""}${note}`,
    ];
  } else if (rating === 3) {
    return [
      `Average experience at ${businessName}.${tagList ? ` The ${tagList} was okay.` : ""}${note}`,
      `Decent visit overall, though there is room for improvement${tagList ? ` regarding ${tagList}` : ""}.${note}`,
      `Fair experience at ${businessName}.${tagList ? ` The ${tagList} was satisfactory.` : ""}${note}`,
    ];
  } else {
    return [
      `Disappointing experience at ${businessName}.${tagList ? ` Issues with ${tagList}.` : ""}${note}`,
      `Expected better from ${businessName}.${tagList ? ` The ${tagList} was not up to mark.` : ""}${note}`,
      `Not satisfied with the visit.${tagList ? ` Needs significant improvement in ${tagList}.` : ""}${note}`,
    ];
  }
}

/**
 * Server-side function to call Gemini and generate 3 honest, distinct review suggestions.
 */
export async function generateReviewSuggestionsWithGemini(
  req: ReviewSuggestionRequest
): Promise<ReviewSuggestionResponse> {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey || apiKey.trim() === "") {
    return {
      suggestions: generateFallbackSuggestions(req),
      isFallback: true,
      message: "Gemini API key is not configured. Displaying template-assisted drafts.",
    };
  }

  const langNames: Record<string, string> = {
    en: "English",
    mr: "Marathi (मराठी)",
    hi: "Hindi (हिन्दी)",
  };

  const userPrompt = `Business Name: "${req.businessName}"
Customer Star Rating: ${req.rating} out of 5 stars
Selected Experience Tags: ${req.selectedTags.length > 0 ? req.selectedTags.join(", ") : "None specified"}
Customer's Own Words: ${req.optionalCustomerText && req.optionalCustomerText.trim() ? `"${req.optionalCustomerText.trim()}"` : "None provided"}
Target Output Language: ${langNames[req.language] || "English"}

Please provide exactly 3 natural, distinct, concise review draft options separated by "---".
Do not invent facts, dishes, prices, or staff names. Reflect the ${req.rating}-star rating honestly.`;

  try {
    const ai = new GoogleGenAI({ apiKey });
    // Use gemini-2.5-flash or gemini-1.5-flash
    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: userPrompt,
      config: {
        systemInstruction: SYSTEM_INSTRUCTION,
        temperature: 0.7,
        maxOutputTokens: 500,
      },
    });

    const responseText = response.text?.trim() || "";

    if (!responseText) {
      return {
        suggestions: generateFallbackSuggestions(req),
        isFallback: true,
        message: "Empty response received from AI. Displaying fallback suggestions.",
      };
    }

    // Split by delimiter "---" or numbered lines if model used numbers
    let rawSuggestions = responseText
      .split(/---|\n{2,}/)
      .map((s) => s.replace(/^\s*(?:Option\s*\d+:?|\d+[\.\)]|\*|-)\s*/gim, "").trim())
      .filter((s) => s.length > 10);

    if (rawSuggestions.length < 3) {
      // Fallback split by newlines
      rawSuggestions = responseText
        .split("\n")
        .map((s) => s.replace(/^\s*(?:Option\s*\d+:?|\d+[\.\)]|\*|-)\s*/gim, "").trim())
        .filter((s) => s.length > 10);
    }

    // Ensure we have exactly 3 suggestions
    if (rawSuggestions.length >= 3) {
      return {
        suggestions: rawSuggestions.slice(0, 3),
        isFallback: false,
      };
    }

    // Supplement if only 1 or 2 parsed
    const fallback = generateFallbackSuggestions(req);
    const combined = [...rawSuggestions, ...fallback].slice(0, 3);
    return {
      suggestions: combined,
      isFallback: false,
    };
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : "Unknown error";
    // Never expose raw API key or full stack trace to client
    return {
      suggestions: generateFallbackSuggestions(req),
      isFallback: true,
      message: `AI service unavailable: ${errorMessage.substring(0, 100)}`,
    };
  }
}
